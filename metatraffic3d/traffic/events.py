"""Incidents and events, so the driving data covers what real streets throw at a car.

Each kind fires at a seeded Poisson rate (per simulated hour) and lasts a while:

* construction: a lane closed with a cone taper and barriers (arterials), the kerb lane
  coned off (sub-roads), or a whole street closed (routing avoids it);
* stalled: a car breaks down in its lane with hazard lights on;
* crash: two cars stopped nose-to-tail, cones behind them, towed away later;
* emergency: an ambulance or fire truck on a siren run; others pull over or change lanes;
* signal_outage: lights fail and the junction becomes an all-way stop;
* hard_brake: a car brakes hard for no visible reason;
* red_light_runner: a driver ignores lights and stop signs for the rest of the trip;
* cut_in: an aggressive driver accepts tiny gaps when changing lanes;
* double_park: a delivery van or truck stops in the lane to unload;
* jaywalkers are generated by the pedestrian model (some reckless).
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from .sim import CLOSED, FREE, LANE, TrafficSim

DEFAULT_RATES = {  # events per simulated hour (whole city)
    "construction": 2.0, "stalled": 5.0, "crash": 2.0, "emergency": 5.0, "signal_outage": 1.5,
    "hard_brake": 40.0, "red_light_runner": 8.0, "cut_in": 15.0, "double_park": 10.0,
}  # fmt: skip
DURATION = {  # seconds (uniform range)
    "construction": (1800, 7200), "stalled": (120, 420), "crash": (300, 900), "signal_outage": (300, 900),
    "double_park": (45, 120),
}  # fmt: skip


@dataclass
class Incident:
    kind: str
    start: float
    end: float
    where: tuple[float, float]
    lanes: list[tuple[int, tuple[float, float]]] = field(default_factory=list)  # closed lane spans
    spots: list[int] = field(default_factory=list)
    dedges: list[int] = field(default_factory=list)  # closed streets
    vehicles: list[int] = field(default_factory=list)
    node: int | None = None
    props: list[tuple[str, float, float, float]] = field(default_factory=list)  # asset, x, y, yaw


class IncidentManager:
    def __init__(self, sim: TrafficSim, seed: int = 0, rates: dict | None = None, initial_construction: int = 3) -> None:
        self.sim = sim
        self.rates = dict(DEFAULT_RATES if rates is None else rates)
        self.initial_construction = initial_construction
        self.reset(seed)

    def reset(self, seed: int = 0) -> None:
        for node in self.sim.net.nodes:  # outages live on the shared network: undo them
            if node.control is not None:
                node.control.outage = False
        self.sim.closed_dedges.clear()
        self.rng = np.random.default_rng(seed + 977)
        self.active: list[Incident] = []
        self.log: list[dict] = []
        self.version = 0
        for _ in range(self.initial_construction):
            self._start("construction")

    @property
    def props(self) -> list[tuple[str, float, float, float]]:
        return [p for inc in self.active for p in inc.props]

    def counts(self) -> dict[str, int]:
        out: dict[str, int] = {}
        for e in self.log:
            out[e["kind"]] = out.get(e["kind"], 0) + 1
        return out

    def step(self, dt: float) -> None:
        t = self.sim.time
        for inc in list(self.active):
            if t >= inc.end or (inc.kind == "emergency" and all(v not in self.sim.vehicles for v in inc.vehicles)):
                self._finish(inc)
        for kind, rate in self.rates.items():
            if self.rng.random() < rate * dt / 3600.0:
                self._start(kind)

    # ------------------------------------------------------------------ start / finish
    def _start(self, kind: str) -> Incident | None:
        inc = getattr(self, f"_start_{kind}")()
        if inc is None:
            return None
        self.active.append(inc)
        self.log.append({"kind": kind, "t": round(self.sim.time, 1), "x": round(inc.where[0], 1), "y": round(inc.where[1], 1)})
        if inc.props:
            self.version += 1
        return inc

    def _finish(self, inc: Incident) -> None:
        sim = self.sim
        for lane, span in inc.lanes:
            blocks = sim.static_blocks.get(lane, [])
            if span in blocks:
                blocks.remove(span)
            if not blocks:
                sim.static_blocks.pop(lane, None)
        for sid in inc.spots:
            if sim.spot_state[sid] == CLOSED:
                sim.spot_state[sid] = FREE
        for d in inc.dedges:
            sim.closed_dedges.discard(d)
        if inc.node is not None:
            sim.net.nodes[inc.node].control.outage = False
        for vid in inc.vehicles:
            v = sim.vehicles.get(vid)
            if v is None:
                continue
            if inc.kind == "crash":
                sim.remove(v)  # towed away
            elif inc.kind == "stalled":
                v.stalled = False
        if inc.dedges:
            sim._refresh_costs()
        self.active.remove(inc)
        if inc.props:
            self.version += 1

    # ------------------------------------------------------------------ helpers
    def _lane_free(self, lane: int, s0: float, s1: float) -> bool:
        return all(not (s0 - 10 < v.s < s1 + v.length + 10) for v in self.sim.lane_veh[lane])

    def _random_npc(self, cond) -> object | None:
        cands = [v for v in self.sim.vehicles.values() if v.kind == "npc" and v.on == LANE and v.state == "drive"
                 and not v.emergency and not v.stalled and cond(v)]  # fmt: skip
        return cands[int(self.rng.integers(len(cands)))] if cands else None

    def _duration(self, kind: str) -> float:
        lo, hi = DURATION.get(kind, (60, 120))
        return float(self.rng.uniform(lo, hi))

    # ------------------------------------------------------------------ kinds
    def _start_construction(self) -> Incident | None:
        sim, net, rng = self.sim, self.sim.net, self.rng
        for _ in range(30):
            de = net.dedges[int(rng.choice(sim.router.ids))]
            if de.length < 90 or de.id in sim.closed_dedges or any(lane_id in sim.static_blocks for lane_id in de.drive):
                continue
            t0 = sim.time
            inc = Incident("construction", t0, t0 + self._duration("construction"), de.center.point_at((de.s0 + de.s1) / 2))
            if len(de.drive) >= 2:  # arterial: close the kerb or median lane with a taper
                k = 0 if rng.random() < 0.6 else len(de.drive) - 1
                lane = net.lanes[de.drive[k]]
                if lane.length < 90:  # lanes are trimmed at junctions, so can be shorter than the edge
                    continue
                length = float(rng.uniform(35, min(110, lane.length - 50)))
                s0 = float(rng.uniform(35, lane.length - length - 10))
                if not self._lane_free(lane.id, s0 - 30, s0 + length):
                    continue
                span = (s0 - 25.0, s0 + length)
                sim.static_blocks.setdefault(lane.id, []).append(span)
                inc.lanes.append((lane.id, span))
                inc.props += self._cone_line(lane, s0 - 25.0, s0 + length, taper=True, toward_left=(k == 0))
                inc.props += self._barriers(lane, s0, s0 + length)
                inc.props.append(("road_work_sign",) + self._kerb_point(de, s0 - 45.0))
                return inc
            if de.park is not None and rng.random() < 0.7:  # sub-road: cone off part of the kerb lane
                lane = net.lanes[de.park]
                if lane.length < 30:
                    continue
                length = float(rng.uniform(20, min(60, lane.length - 10)))
                s0 = float(rng.uniform(5, max(lane.length - length - 5, 5.1)))
                spots = [sid for sid in lane.spots if s0 - 3 < net.spots[sid].s < s0 + length + 3 and sim.spot_state[sid] == FREE]
                for sid in spots:
                    sim.spot_state[sid] = CLOSED
                inc.spots = spots
                inc.props += self._cone_line(lane, s0, s0 + length, taper=False, toward_left=True)
                inc.props.append(("excavator",) + lane.path.pose_at(s0 + length / 2))
                return inc
            e = net.edges[de.edge]  # whole street closed: barriers at both entrances
            a, b = net.dedges[2 * e.id], net.dedges[2 * e.id + 1]
            lanes_in = list(a.drive + b.drive)
            if any(sim.conn_busy[c] for lane_id in lanes_in for c in sim.lane_in_conns[lane_id]):
                continue  # somebody is turning in right now
            for d in (a, b):
                for lane_id in d.drive:
                    span = (0.0, 4.0)  # cars already inside may drive out
                    sim.static_blocks.setdefault(lane_id, []).append(span)
                    inc.lanes.append((lane_id, span))
                sim.closed_dedges.add(d.id)
                inc.dedges.append(d.id)
                for s_end in (2.0,):
                    x, y, h = d.center.pose_at(d.s0 + s_end)
                    for off in np.linspace(-e.cls.half_width + 1, e.cls.half_width - 1, 4):
                        inc.props.append(("barrier", x + math.sin(h) * off, y - math.cos(h) * off, h + math.pi / 2))
            sim._refresh_costs()
            return inc
        return None

    def _kerb_point(self, de, s: float) -> tuple[float, float, float]:
        x, y, h = de.center.pose_at(min(max(de.s0 + s, de.s0), de.s1))
        off = de.cls.half_width + 0.8
        return x + math.sin(h) * off, y - math.cos(h) * off, h + math.pi

    def _cone_line(self, lane, s0: float, s1: float, taper: bool, toward_left: bool = True):
        """Cones along the edge of a closed lane on the open side; with a 25 m diagonal taper."""
        out = []
        target = lane.width / 2 if toward_left else -lane.width / 2  # lateral offset, + = left
        for s in np.arange(max(s0, 0.5), min(s1, lane.length), 5.0):
            x, y, h = lane.path.pose_at(s)
            frac = min(max((s - s0) / 25.0, 0.0), 1.0) if taper else 1.0
            lat = -target + 2 * target * frac
            out.append(("traffic_cone", x - math.sin(h) * lat, y + math.cos(h) * lat, h))
        return out

    def _barriers(self, lane, s0: float, s1: float):
        out = []
        for s in (s0, s1):
            if 0 < s < lane.length:
                x, y, h = lane.path.pose_at(s)
                out.append(("barrier", x, y, h + math.pi / 2))
        return out

    def _start_stalled(self) -> Incident | None:
        net = self.sim.net
        v = self._random_npc(lambda v: net.lanes[v.elem].length - v.s > 30 and v.s > 15
                             and len(net.dedges[net.lanes[v.elem].dedge].drive) > 1)  # others can pass  # fmt: skip
        if v is None:
            return None
        self.sim._drop_junction(v)
        v.stalled = True
        x, y, _ = self.sim.pose(v)
        return Incident("stalled", self.sim.time, self.sim.time + self._duration("stalled"), (x, y), vehicles=[v.id])

    def _start_crash(self) -> Incident | None:
        sim = self.sim

        def has_follower(v):
            if len(sim.net.dedges[sim.net.lanes[v.elem].dedge].drive) < 2:
                return False  # crashes block one lane of a multi-lane road
            lst = sim.lane_veh[v.elem]
            i = lst.index(v)
            return i + 1 < len(lst) and lst[i + 1].kind == "npc" and v.s - lst[i + 1].s < 30 and v.s > 25
        v = self._random_npc(has_follower)
        if v is None:
            return None
        lst = sim.lane_veh[v.elem]
        f = lst[lst.index(v) + 1]
        f.s = v.s - v.length - 0.3
        for o in (v, f):
            sim._drop_junction(o)
            o.stalled, o.v = True, 0.0
        lane = sim.net.lanes[v.elem]
        props = self._cone_line(lane, f.s - f.length - 14, f.s - f.length - 2, taper=True)
        x, y, _ = sim.pose(v)
        return Incident("crash", sim.time, sim.time + self._duration("crash"), (x, y), vehicles=[v.id, f.id], props=props)

    def _start_emergency(self) -> Incident | None:
        sim = self.sim
        kind = "ambulance" if self.rng.random() < 0.6 else "fire_truck"
        v = sim.spawn_npc(vtype=kind)
        if v is None:
            return None
        v.emergency = True
        v.v = 8.0
        x, y, _ = sim.pose(v)
        return Incident("emergency", sim.time, sim.time + 1800, (x, y), vehicles=[v.id])

    def _start_signal_outage(self) -> Incident | None:
        sig = [n for n in self.sim.net.nodes if n.control is not None and n.control.kind == "signal" and not n.control.outage]
        if not sig:
            return None
        n = sig[int(self.rng.integers(len(sig)))]
        n.control.outage = True
        return Incident("signal_outage", self.sim.time, self.sim.time + self._duration("signal_outage"), n.pos, node=n.id)

    def _start_hard_brake(self) -> Incident | None:
        v = self._random_npc(lambda v: v.v > 6.0)
        if v is None:
            return None
        v.hard_brake = float(self.rng.uniform(1.5, 3.0))
        x, y, _ = self.sim.pose(v)
        return Incident("hard_brake", self.sim.time, self.sim.time + 5, (x, y), vehicles=[v.id])

    def _start_red_light_runner(self) -> Incident | None:
        v = self._random_npc(lambda v: not v.reckless)
        if v is None:
            return None
        v.reckless = True
        x, y, _ = self.sim.pose(v)
        return Incident("red_light_runner", self.sim.time, self.sim.time + 1, (x, y), vehicles=[v.id])

    def _start_cut_in(self) -> Incident | None:
        v = self._random_npc(lambda v: len(self.sim.net.dedges[self.sim.net.lanes[v.elem].dedge].drive) > 1)
        if v is None:
            return None
        v.aggressive = True
        x, y, _ = self.sim.pose(v)
        return Incident("cut_in", self.sim.time, self.sim.time + 1, (x, y), vehicles=[v.id])

    def _start_double_park(self) -> Incident | None:
        sim = self.sim
        v = self._random_npc(lambda v: v.vtype in ("delivery", "truck", "van", "garbage_truck")
                             and len(sim.net.dedges[sim.net.lanes[v.elem].dedge].drive) == 1
                             and 20 < v.s < sim.net.lanes[v.elem].length - 25)  # fmt: skip
        if v is None:
            return None
        sim.stop_here(v, self._duration("double_park"))
        x, y, _ = sim.pose(v)
        return Incident("double_park", sim.time, sim.time + 1, (x, y), vehicles=[v.id])
